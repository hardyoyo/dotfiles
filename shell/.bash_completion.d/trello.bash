    local i cur prev opts cmds
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"
    cmd=""
    opts=""

    for i in ${COMP_WORDS[@]}
    do
        case "${i}" in
            trello)
                cmd="trello"
                ;;
            
            auto_complete)
                cmd+="__auto_complete"
                ;;
            board)
                cmd+="__board"
                ;;
            board_details)
                cmd+="__board_details"
                ;;
            card)
                cmd+="__card"
                ;;
            card_id_by_id_short)
                cmd+="__card_id_by_id_short"
                ;;
            card_id_by_substring)
                cmd+="__card_id_by_substring"
                ;;
            cards)
                cmd+="__cards"
                ;;
            checklists)
                cmd+="__checklists"
                ;;
            edit_card)
                cmd+="__edit_card"
                ;;
            help)
                cmd+="__help"
                ;;
            list_id_by_substring)
                cmd+="__list_id_by_substring"
                ;;
            lists)
                cmd+="__lists"
                ;;
            move)
                cmd+="__move"
                ;;
            new)
                cmd+="__new"
                ;;
            new_card)
                cmd+="__new_card"
                ;;
            open_board)
                cmd+="__open_board"
                ;;
            show)
                cmd+="__show"
                ;;
            *)
                ;;
        esac
    done

    case "${cmd}" in
        trello)
            opts=" -h -V  --help --version   board_details card cards checklists lists edit_card new_card board open_board card_id_by_substring card_id_by_id_short list_id_by_substring new move show auto_complete help"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 1 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        
        trello__auto_complete)
            opts=" -h -V  --help --version  <SHELL> "
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        trello__board)
            opts=" -q -R -h -V  --quiet --raw_response --help --version  "
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        trello__board_details)
            opts=" -q -R -h -V -t  --quiet --raw_response --help --version --template  "
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                
                --template)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                    -t)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        trello__card)
            opts=" -q -R -h -V -t  --quiet --raw_response --help --version --template  <CARD_ID> "
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                
                --template)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                    -t)
                    COMPREPLY=($(compgen -f "${cur}"))
                    return 0
                    ;;
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        trello__card_id_by_id_short)
